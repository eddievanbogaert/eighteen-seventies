#!/usr/bin/env python3
"""Build the author's verification worksheet from CLAIMS.md.

    python3 tools/review_queue.py              # print the worksheet
    python3 tools/review_queue.py --write      # write notes/REVIEW-QUEUE.md

Why this exists. `verified: "y"` in CLAIMS.md means one specific thing: the
author looked at the source and saw the claim in it. An agent can check a
claim and record that it did, which is what `verified: "n"` plus a notes field
means here, but it cannot sign the author's name. So the rows pile up waiting,
and the pile looks daunting.

It is less daunting than it looks, because the rows cluster. Most claims come
from a handful of documents, and several claims usually sit on one page. Open
the page once, check every claim that lives on it, and a dozen rows close
together. This script groups the queue that way: by source, then by the page
the notes field names, so the author's pass follows the documents rather than
the ledger's row order.

It changes nothing. It only reads CLAIMS.md and prints what is outstanding.
"""

from __future__ import annotations

import argparse
import collections
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
CLAIMS = ROOT / "research" / "CLAIMS.md"
OUT = ROOT / "notes" / "REVIEW-QUEUE.md"

PAGE = re.compile(
    r"(printed p+\.?\s*\d+|page image of [^.;]+|notebook p+\.?\s*\d+[^.;]*|"
    r"specification p\.\s*\d+|index p\.\s*[a-z0-9]+|leaf \d+)",
    re.I,
)


def rows():
    for line in CLAIMS.read_text(encoding="utf-8").splitlines():
        if not line.startswith("| C") or line.count("|") < 6:
            continue
        c = [x.strip() for x in line.strip("|").split("|")]
        yield {"id": c[0], "claim": c[1], "chapter": c[2],
               "source": c[3], "verified": c[4].strip('"'), "notes": c[5]}


def locator(note: str) -> str:
    m = PAGE.search(note)
    return m.group(1).strip().rstrip(",") if m else "— locator not named —"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()

    all_rows = list(rows())
    pending = [r for r in all_rows if r["verified"] != "y"]
    done = len(all_rows) - len(pending)

    by_source: dict[str, dict[str, list]] = collections.defaultdict(
        lambda: collections.defaultdict(list)
    )
    for r in pending:
        by_source[r["source"]][locator(r["notes"])].append(r)

    out = []
    w = out.append
    w("# Review queue\n")
    w("Generated by `tools/review_queue.py`. Do not edit by hand — edit "
      "`research/CLAIMS.md` and regenerate.\n")
    w(f"**{len(pending)} claims awaiting the author's reading. "
      f"{done} verified.**\n")
    w("Grouped by source, then by page, so one opened page closes several "
      "rows. To approve a row, set its `verified` column in `CLAIMS.md` to "
      '`"y"`. To reject it, leave it `"n"` and say why in its notes — a row '
      "that failed is worth more than a blank, because it stops the same "
      "wrong claim being reintroduced.\n")
    w("Nothing here is verified by the existence of this file.\n")

    for source in sorted(by_source):
        n = sum(len(v) for v in by_source[source].values())
        w(f"\n## `{source}` — {n} claim(s)\n")
        for loc in sorted(by_source[source]):
            w(f"\n**{loc}**\n")
            for r in sorted(by_source[source][loc], key=lambda x: x["id"]):
                claim = re.sub(r"\s+", " ", r["claim"])
                if len(claim) > 300:
                    claim = claim[:297] + "..."
                w(f"- `{r['id']}` (ch {r['chapter']}) — {claim}")

    text = "\n".join(out) + "\n"
    if args.write:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}: {len(pending)} pending, {done} verified")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
